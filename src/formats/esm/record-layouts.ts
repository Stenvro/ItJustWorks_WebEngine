// layout.ts. After xEdit's TES5 definitions (wbDefinitionsTES5.pas) and UESP's "Skyrim Mod:Mod
// File Format"; `format-census esm` decodes every subrecord of every record with these and
// fails on any that does not consume its data exactly. Names follow xEdit's where it has them;
// `unknown` marks bytes xEdit does not name either. VMAD is read by vmad.ts.

