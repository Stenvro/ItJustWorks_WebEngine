  '| counters:u32 textures:u32 addons:u32 (file:u32 extension:c4 folder:u32)[textures] addon:u32[addons] || (file:u32 extension:c4 folder:u32)[] || (filePc:u64 fileConsole:u64 folder:u64)[]';
