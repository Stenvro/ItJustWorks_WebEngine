// Navigation meshes (NAVM): where actors can walk, as triangles over the floors, stairs and
// ramps of a cell, with their neighbours (in the mesh, or over links into other meshes), the
// doors on them and a search grid. The NVNM field (version 12 in SSE): UESP "Skyrim Mod:Mod File
// Format/NVNM Field", xEdit (wbDefinitionsTES5 wbNVNM), OpenMW's ESM4 loader
// (components/esm4/loadnavm), CommonLibSSE (BSNavmesh). Layout: docs/formats/esm.md
// ("Navigation meshes"). Platform-independent.

import { BinaryReader, FormatError } from '../formats/binary-reader.ts';
import type { GameRecord, RecordDatabase } from './record-db.ts';

/** The NVNM version of Skyrim (and SSE). */
export const NAVMESH_VERSION = 12;

/** NVNM triangle flags (xEdit). */
export const NavmeshFlag = {
  edge01Link: 0x0001,
  edge12Link: 0x0002,
  edge20Link: 0x0004,
  deleted: 0x0008,
  noLargeCreatures: 0x0010,
  overlapping: 0x0020,
  preferred: 0x0040,
  water: 0x0200,
  door: 0x0400,
  found: 0x0800,
} as const;

export interface NavmeshTriangle {
  /** Vertex indices. */
  readonly vertices: readonly [number, number, number];
  /**
   * What lies across each edge (0–1, 1–2, 2–0): a triangle of this mesh, −1 for none, or, with
   * the edge's link flag (NavmeshFlag.edge01Link …), an index into `links`. Read it with
   * triangleNeighbour.
   */
  readonly edges: readonly [number, number, number];
  /** NavmeshFlag bits. */
  readonly flags: number;
  /**
   * Cover along edges 0–1 (bits 0–5) and 1–2 (bits 6–11): a 4-bit value (0 open, 1 wall
   * without cover, 2 ledge, 4–14 cover value × 16 units high, 15 full cover), then left (0x10)
   * and right (0x20) flags; 0x4000 generated by the Creation Kit (xEdit).
   */
  readonly cover: number;
}

/** NavmeshLink types (CommonLibSSE EDGE_EXTRA_INFO_TYPE). */
export const NavmeshLinkType = {
  /** The edge continues into the other mesh's triangle (a cell border). */
  portal: 0,
  /** A jump from below a ledge up onto the triangle on top. */
  ledgeUp: 1,
  /** A drop from a ledge down onto the triangle below. */
  ledgeDown: 2,
  enableDisablePortal: 3,
} as const;

/** A triangle's edge leading to a triangle of another (or, for ledges, the same) mesh. */
export interface NavmeshLink {
  /** NavmeshLinkType. */
  readonly type: number;
  /** The NAVM it leads into. */
  readonly navmesh: number;
  readonly triangle: number;
}

/** A triangle in front of a door: the door reference. */
export interface NavmeshDoor {
  readonly triangle: number;
  /** Always PathingType.door. */
  readonly type: number;
  readonly door: number;
}

export interface Navmesh {
  readonly formId: number;
  /** The worldspace, 0 for interiors. */
  readonly world: number;
  /** Interiors: the cell; worldspaces: its grid (x, y). */
  readonly cell: number | { readonly x: number; readonly y: number };
  /** Game units, xyz per vertex, world coordinates. */
  readonly vertices: Float32Array;
  readonly triangles: readonly NavmeshTriangle[];
  readonly links: readonly NavmeshLink[];
  readonly doors: readonly NavmeshDoor[];
  /** Triangles with cover. */
  readonly coverTriangles: readonly number[];
  /** The search grid: `divisor`² cells over the bounds, each listing its triangles. */
  readonly grid: {
    readonly divisor: number;
    readonly cellSize: readonly [number, number];
    readonly min: readonly [number, number, number];
    readonly max: readonly [number, number, number];
    readonly cells: readonly (readonly number[])[];
  };
}

/**
 * Type hashes of the engine's pathing classes, stored before the data they describe: CRC-32 of
 * the class name, initial value 0 and no final XOR (xEdit wbCRCValuesEnum; CommonLibSSE
 * BSPathingCell::GetType).
 */
export const PathingType = {
  /** "PathingCell": a cell, or a worldspace and grid position. */
  cell: 0xa5e9a03c,
  /** "PathingDoor": a door reference. */
  door: 0xe48b73f3,
} as const;

/** Reads a NAVM's NVNM field; undefined if the record has none (a deleted navmesh). */
export function parseNavmesh(record: GameRecord): Navmesh | undefined {
  const nvnm = record.fields.first('NVNM');
  if (!nvnm) return undefined;
  const reader = new BinaryReader(nvnm);
  const version = reader.u32();
  if (version !== NAVMESH_VERSION) {
    throw new FormatError(
      `NVNM version ${String(version)}, expected ${String(NAVMESH_VERSION)}`,
      0,
    );
  }
  const formIdAt = (): number => {
    const offset = reader.offset;
    reader.skip(4);
    return record.formIdAt(nvnm, offset);
  };
  const { world, cell } = readPathingCell(reader, formIdAt);
  const vertexCount = reader.u32();
  const vertices = new Float32Array(vertexCount * 3);
  for (let i = 0; i < vertices.length; i++) vertices[i] = reader.f32();
  const triangleCount = reader.u32();
  const triangles: NavmeshTriangle[] = [];
  for (let i = 0; i < triangleCount; i++) {
    const a = reader.u16();
    const b = reader.u16();
    const c = reader.u16();
    if (a >= vertexCount || b >= vertexCount || c >= vertexCount) {
      throw new FormatError(`NVNM triangle ${String(i)} names a missing vertex`, reader.offset);
    }
    const edges: [number, number, number] = [reader.i16(), reader.i16(), reader.i16()];
    triangles.push({ vertices: [a, b, c], edges, flags: reader.u16(), cover: reader.u16() });
  }
  const links: NavmeshLink[] = [];
  const linkCount = reader.u32();
  for (let i = 0; i < linkCount; i++) {
    const type = reader.u32();
    const navmesh = formIdAt();
    links.push({ type, navmesh, triangle: reader.u16() });
  }
  const doors: NavmeshDoor[] = [];
  const doorCount = reader.u32();
  for (let i = 0; i < doorCount; i++) {
    const triangle = reader.u16();
    const type = reader.u32();
    doors.push({ triangle, type, door: formIdAt() });
  }
  const coverTriangles: number[] = [];
  const coverCount = reader.u32();
  for (let i = 0; i < coverCount; i++) coverTriangles.push(reader.u16());
  const divisor = reader.u32();
  const cellSize: [number, number] = [reader.f32(), reader.f32()];
  const min: [number, number, number] = [reader.f32(), reader.f32(), reader.f32()];
  const max: [number, number, number] = [reader.f32(), reader.f32(), reader.f32()];
  const cells: number[][] = [];
  for (let i = 0; i < divisor * divisor; i++) {
    const count = reader.u32();
    const list: number[] = [];
    for (let j = 0; j < count; j++) list.push(reader.u16());
    cells.push(list);
  }
  if (reader.remaining !== 0) {
    throw new FormatError(`NVNM: ${String(reader.remaining)} bytes left over`, reader.offset);
  }
  return {
    formId: record.formId,
    world,
    cell,
    vertices,
    triangles,
    links,
    doors,
    coverTriangles,
    grid: { divisor, cellSize, min, max, cells },
  };
}

/**
 * A pathing cell (NVNM and NAVI): its type hash, the worldspace (form id, 0 for interiors), then
 * for interiors the cell (form id), for worldspaces the grid position (y i16, x i16; xEdit
 * wbNVNMParentDecider).
 */
export function readPathingCell(
  reader: BinaryReader,
  formId: () => number,
): { world: number; cell: Navmesh['cell'] } {
  const type = reader.u32();
  if (type !== PathingType.cell) {
    throw new FormatError(`pathing cell of type ${type.toString(16)}`, reader.offset - 4);
  }
  const world = formId();
  if (world === 0) return { world, cell: formId() };
  const y = reader.i16();
  const x = reader.i16();
  return { world, cell: { x, y } };
}

/**
 * What lies across a triangle's edge (0: 0–1, 1: 1–2, 2: 2–0): a triangle of the same mesh (its
 * index), a link (to another mesh's triangle, or a ledge to this mesh's), or undefined for none.
 */
export function triangleNeighbour(
  navmesh: Navmesh,
  triangle: number,
  edge: number,
): number | NavmeshLink | undefined {
  const t = navmesh.triangles[triangle];
  const value = t?.edges[edge];
  if (t === undefined || value === undefined || value < 0) return undefined;
  if ((t.flags & (NavmeshFlag.edge01Link << edge)) !== 0) return navmesh.links[value];
  return value < navmesh.triangles.length ? value : undefined;
}

/** A triangle's corners (game units). */
export function navmeshTriangle(
  navmesh: Navmesh,
  index: number,
): [[number, number, number], [number, number, number], [number, number, number]] {
  const triangle = navmesh.triangles[index];
  const corner = (vertex: number): [number, number, number] => [
    navmesh.vertices[vertex * 3] ?? 0,
    navmesh.vertices[vertex * 3 + 1] ?? 0,
    navmesh.vertices[vertex * 3 + 2] ?? 0,
  ];
  const [a = 0, b = 0, c = 0] = triangle?.vertices ?? [];
  return [corner(a), corner(b), corner(c)];
}

/** A point lies on a navigation mesh within this height of it (game units): the meshes lie a
 * little above or below the floors they follow. */
export const NAVMESH_TOLERANCE = 24;

/** The navigation meshes of a cell (its NAVM children), deleted ones left out. */
export async function cellNavmeshes(db: RecordDatabase, cell: number): Promise<Navmesh[]> {
  const meshes: Navmesh[] = [];
  for (const id of db.cellReferences(cell)) {
    const location = db.locate(id);
    if (!location || db.typeAt(location) !== 'NAVM') continue;
    const record = await db.read(location);
    if (record.deleted) continue;
    const navmesh = parseNavmesh(record);
    if (navmesh) meshes.push(navmesh);
  }
  return meshes;
}

/** The size of the bins NavmeshSurface sorts triangles into (game units). */
const SURFACE_BIN = 256;
/**
 * How far above or below a point the navmesh nearest to it may be: an actor placed on a table,
 * a bench or a hearth's logs stands on the floor round it (units).
 */
export const NEAREST_TOLERANCE = 128;

/**
 * The walkable surface of a set of navigation meshes, for asking whether actors walk at a
 * point: triangles sorted into square bins by their bounds.
 */
export class NavmeshSurface {
  readonly #meshes: readonly Navmesh[];
  readonly #bins = new Map<string, [number, number][]>();

  constructor(meshes: readonly Navmesh[]) {
    this.#meshes = meshes;
    meshes.forEach((navmesh, mesh) => {
      navmesh.triangles.forEach((triangle, index) => {
        if ((triangle.flags & NavmeshFlag.deleted) !== 0) return;
        const corners = navmeshTriangle(navmesh, index);
        const xs = corners.map((corner) => corner[0]);
        const ys = corners.map((corner) => corner[1]);
        for (let bx = binOf(Math.min(...xs)); bx <= binOf(Math.max(...xs)); bx++) {
          for (let by = binOf(Math.min(...ys)); by <= binOf(Math.max(...ys)); by++) {
            const key = `${String(bx)},${String(by)}`;
            const list = this.#bins.get(key) ?? [];
            list.push([mesh, index]);
            this.#bins.set(key, list);
          }
        }
      });
    });
  }

  /** The navigation meshes it is made of. */
  get meshes(): readonly Navmesh[] {
    return this.#meshes;
  }

  /**
   * The navmesh's height over a point nearest to `z`, if it covers the point within
   * `tolerance` of that height (navmeshes lie a little above or below the floors they follow).
   */
  heightNear(x: number, y: number, z: number, tolerance: number): number | undefined {
    return this.near(x, y, z, tolerance)?.height;
  }

  /** As heightNear, with the navmesh and triangle there. */
  near(
    x: number,
    y: number,
    z: number,
    tolerance: number,
  ): { readonly navmesh: Navmesh; readonly triangle: number; readonly height: number } | undefined {
    let best: { navmesh: Navmesh; triangle: number; height: number } | undefined;
    for (const [mesh, index] of this.#bins.get(`${String(binOf(x))},${String(binOf(y))}`) ?? []) {
      const navmesh = this.#meshes[mesh];
      if (!navmesh) continue;
      const [a, b, c] = navmeshTriangle(navmesh, index);
      // Barycentric coordinates in the horizontal plane.
      const det = (b[1] - c[1]) * (a[0] - c[0]) + (c[0] - b[0]) * (a[1] - c[1]);
      if (Math.abs(det) < 1e-9) continue;
      const u = ((b[1] - c[1]) * (x - c[0]) + (c[0] - b[0]) * (y - c[1])) / det;
      const v = ((c[1] - a[1]) * (x - c[0]) + (a[0] - c[0]) * (y - c[1])) / det;
      const w = 1 - u - v;
      if (u < -1e-6 || v < -1e-6 || w < -1e-6) continue;
      const height = u * a[2] + v * b[2] + w * c[2];
      if (Math.abs(height - z) > tolerance) continue;
      if (best === undefined || Math.abs(height - z) < Math.abs(best.height - z)) {
        best = { navmesh, triangle: index, height };
      }
    }
    return best;
  }

  /**
   * The point of the navmesh nearest to a point (horizontally, within `reach`), on a
   * triangle within `tolerance` of its height: where an actor placed off the navmesh (on a
   * table, in a hearth) stands instead.
   */
  nearest(
    x: number,
    y: number,
    z: number,
    reach: number,
    tolerance: number,
  ): { readonly point: [number, number, number]; readonly distance: number } | undefined {
    // A point not on any map (not finite, or beyond where its bins count up) is near nothing.
    if (!(Math.abs(x) + Math.abs(y) + reach < MAX_COORDINATE)) return undefined;
    let best: { point: [number, number, number]; distance: number } | undefined;
    const seen = new Set<string>();
    for (let bx = binOf(x - reach); bx <= binOf(x + reach); bx++) {
      for (let by = binOf(y - reach); by <= binOf(y + reach); by++) {
        for (const [mesh, index] of this.#bins.get(`${String(bx)},${String(by)}`) ?? []) {
          const key = `${String(mesh)}:${String(index)}`;
          if (seen.has(key)) continue;
          seen.add(key);
          const navmesh = this.#meshes[mesh];
          if (!navmesh) continue;
          const point = closestOnTriangle(navmeshTriangle(navmesh, index), x, y);
          if (!point || Math.abs(point[2] - z) > tolerance) continue;
          const distance = Math.hypot(point[0] - x, point[1] - y);
          if (distance <= reach && (best === undefined || distance < best.distance)) {
            best = { point, distance };
          }
        }
      }
    }
    return best;
  }
}

/**
 * The point of a triangle nearest to (x, y) in the horizontal plane, with the triangle's
 * height there; undefined for a triangle with no area.
 */
type Corner = readonly [number, number, number];

function closestOnTriangle(
  [[ax, ay, az], [bx, by, bz], [cx, cy, cz]]: readonly [Corner, Corner, Corner],
  x: number,
  y: number,
): [number, number, number] | undefined {
  const det = (by - cy) * (ax - cx) + (cx - bx) * (ay - cy);
  if (Math.abs(det) < 1e-9) return undefined;
  const at = (px: number, py: number): [number, number, number] => {
    const u = ((by - cy) * (px - cx) + (cx - bx) * (py - cy)) / det;
    const v = ((cy - ay) * (px - cx) + (ax - cx) * (py - cy)) / det;
    return [px, py, u * az + v * bz + (1 - u - v) * cz];
  };
  const u = ((by - cy) * (x - cx) + (cx - bx) * (y - cy)) / det;
  const v = ((cy - ay) * (x - cx) + (ax - cx) * (y - cy)) / det;
  if (u >= 0 && v >= 0 && u + v <= 1) return at(x, y);
  // Outside: the nearest point of its edges.
  let best: [number, number] = [ax, ay];
  let nearest = Infinity;
  for (const [px, py, qx, qy] of [
    [ax, ay, bx, by],
    [bx, by, cx, cy],
    [cx, cy, ax, ay],
  ] as const) {
    const dx = qx - px;
    const dy = qy - py;
    const length = dx * dx + dy * dy;
    const t = length > 0 ? Math.min(1, Math.max(0, ((x - px) * dx + (y - py) * dy) / length)) : 0;
    const ex = px + dx * t;
    const ey = py + dy * t;
    const distance = Math.hypot(ex - x, ey - y);
    if (distance < nearest) {
      nearest = distance;
      best = [ex, ey];
    }
  }
  return at(best[0], best[1]);
}

const binOf = (v: number): number => Math.floor(v / SURFACE_BIN);
/** Farther out than any worldspace reaches (units): a coordinate past it is a fault. */
const MAX_COORDINATE = 1e7;
