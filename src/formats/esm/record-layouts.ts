/** WTHR's cloud textures: "00TX" to "L0TX", one per layer (the first character counts up). */
export function isCloudTextureCode(type: string, code: string): boolean {
  return type === 'WTHR' && code.endsWith('0TX') && code.charCodeAt(0) >= 0x30;
}

/** IMAD's animated colour and value channels: "\0IAD" to "TIAD" and "@IAD" (key lists). */
export function isImageSpaceKeyCode(type: string, code: string): boolean {
  return type === 'IMAD' && code.endsWith('IAD');
}

/** The layout of one subrecord of a record type, or undefined when the tables have none. */
export function subrecordLayout(type: string, code: string): string | undefined {
  const own = RECORD_LAYOUTS[type]?.[code];
  if (own !== undefined) return own;
  if (isCloudTextureCode(type, code)) return 'texture:z';
  if (isImageSpaceKeyCode(type, code)) return '(time:f32 value:f32)[]';
  return COMMON_LAYOUTS[code];
}

/** One record's subrecords decoded by the tables, with what did not decode. */
export interface DecodedRecord {
  /** Each subrecord's value, in record order (undefined where it did not decode). */
  readonly values: readonly { readonly code: string; readonly value: LayoutValue | undefined }[];
  /** Problems by subrecord code (layout mismatches, bad form ids, unresolved string ids). */
  readonly problems: ReadonlyMap<string, readonly LayoutProblem[]>;
  /** Codes with no layout. */
  readonly unknown: readonly string[];
}

/**
 * Decodes every subrecord of a record by the tables (VMAD by vmad.ts). `context` gives the
 * plugin's localized flag, master count and (to check string ids) its string tables.
 */
export function decodeRecord(
  type: string,
  fields: readonly Field[],
  context: Omit<LayoutContext, 'previous'>,
): DecodedRecord {
  const values: { code: string; value: LayoutValue | undefined }[] = [];
  const problems = new Map<string, LayoutProblem[]>();
  const unknown: string[] = [];
  const last = new Map<string, Uint8Array>();
  const fieldContext: LayoutContext = { ...context, previous: (code) => last.get(code) };
  for (const field of fields) {
    const found: LayoutProblem[] = [];
    let value: LayoutValue | undefined;
    if (field.type === 'VMAD') {
      try {
        const unread = parseVmad(field.data, type).unread ?? 0;
        if (unread > 0) found.push({ kind: 'size', detail: `${unread} bytes left` });
      } catch (error) {
        found.push({
          kind: 'size',
          detail: error instanceof Error ? error.message : String(error),
        });
      }
    } else {
      const layout = subrecordLayout(type, field.type);
      if (layout === undefined) unknown.push(field.type);
      else value = decodeLayout(compileLayout(layout), field.data, fieldContext, found);
    }
    if (found.length > 0) problems.set(field.type, [...(problems.get(field.type) ?? []), ...found]);
    values.push({ code: field.type, value });
    last.set(field.type, field.data);
  }
  return { values, problems, unknown };
}

/** Decodes one subrecord by the tables; undefined when it has no layout or does not fit. */
export function decodeSubrecord(
  type: string,
  code: string,
  data: Uint8Array,
  context: LayoutContext,
  problems: LayoutProblem[] = [],
): LayoutValue | undefined {
  const layout = subrecordLayout(type, code);
  return layout === undefined
    ? undefined
    : decodeLayout(compileLayout(layout), data, context, problems);
}
